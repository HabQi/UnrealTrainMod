package com.unrealtrainmod.client.mixin;

import com.unrealtrainmod.client.compat.iris.IrisCompat;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Pseudo;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Pseudo
@Mixin(targets = "net.irisshaders.iris.shadows.ShadowRenderer", remap = false)
public abstract class IrisShadowRendererMixin {
    @Inject(method = "renderShadows", at = @At(value = "INVOKE", target =
            "Lnet/irisshaders/iris/shadows/ShadowRenderer;copyPreTranslucentDepth(Lnet/irisshaders/iris/mixin/LevelRendererAccessor;)V"))
    private void unrealtrainmod$trackShadows(CallbackInfo callback) {
        IrisCompat.renderTrackShadows();
    }
}
